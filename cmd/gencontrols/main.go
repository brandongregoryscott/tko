// Command gencontrols generates the key map and README tables from controls.json.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"strings"
)

type binding struct {
	ID          string   `json:"id"`
	Keys        []string `json:"keys"`
	HelpKey     string   `json:"help_key"`
	Help        string   `json:"help"`
	Description string   `json:"description"`
}

type section struct {
	Title    string    `json:"title"`
	Intro    string    `json:"intro,omitempty"`
	Outro    string    `json:"outro,omitempty"`
	Bindings []binding `json:"bindings"`
}

type config struct {
	Sections  []section  `json:"sections"`
	ShortHelp []string   `json:"short_help"`
	FullHelp  [][]string `json:"full_help"`
}

const begin = "<!-- BEGIN GENERATED KEY BINDINGS -->"
const end = "<!-- END GENERATED KEY BINDINGS -->"

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "check generated files without writing")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	data, err := os.ReadFile(filepath.Join(root, "controls.json"))
	if err != nil {
		return err
	}
	c, err := parseConfig(data)
	if err != nil {
		return err
	}
	code, err := renderGo(c)
	if err != nil {
		return err
	}
	readmePath := filepath.Join(root, "README.md")
	readme, err := os.ReadFile(readmePath)
	if err != nil {
		return err
	}
	updated, err := updateReadme(string(readme), renderMarkdown(c))
	if err != nil {
		return err
	}
	for _, output := range []struct {
		path string
		data []byte
	}{
		{filepath.Join(root, "internal/ui/keymap.go"), code},
		{readmePath, []byte(updated)},
	} {
		old, err := os.ReadFile(output.path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if bytes.Equal(old, output.data) {
			continue
		}
		if check {
			return fmt.Errorf("%s is out of date; run go generate ./...", output.path)
		}
		if err := os.WriteFile(output.path, output.data, 0644); err != nil {
			return err
		}
	}
	return nil
}

func parseConfig(data []byte) (config, error) {
	var c config
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&c); err != nil {
		return c, err
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		return c, fmt.Errorf("expected a single JSON object")
	}
	ids, keys := map[string]bool{}, map[string]string{}
	if len(c.Sections) == 0 {
		return c, fmt.Errorf("no control sections")
	}
	for _, s := range c.Sections {
		if s.Title == "" || len(s.Bindings) == 0 {
			return c, fmt.Errorf("each section needs a title and bindings")
		}
		for _, b := range s.Bindings {
			if !token.IsIdentifier(b.ID) || !token.IsExported(b.ID) || ids[b.ID] || b.ID == "ShortHelp" || b.ID == "FullHelp" {
				return c, fmt.Errorf("invalid or duplicate action ID %q", b.ID)
			}
			ids[b.ID] = true
			if len(b.Keys) == 0 || b.HelpKey == "" || b.Help == "" || b.Description == "" {
				return c, fmt.Errorf("%s needs keys, help_key, help, and description", b.ID)
			}
			for _, k := range b.Keys {
				if k == "" {
					return c, fmt.Errorf("%s has an empty key", b.ID)
				}
				if owner, ok := keys[k]; ok {
					return c, fmt.Errorf("key %q is shared by %s and %s", k, owner, b.ID)
				}
				keys[k] = b.ID
			}
		}
	}
	if len(c.ShortHelp) == 0 || len(c.FullHelp) == 0 {
		return c, fmt.Errorf("help layouts must not be empty")
	}
	for _, layout := range [][][]string{{c.ShortHelp}, c.FullHelp} {
		seen := map[string]bool{}
		for _, group := range layout {
			if len(group) == 0 {
				return c, fmt.Errorf("empty help group")
			}
			for _, id := range group {
				if !ids[id] || seen[id] {
					return c, fmt.Errorf("unknown or repeated help action %q", id)
				}
				seen[id] = true
			}
		}
	}
	return c, nil
}

func renderGo(c config) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by go generate from controls.json; DO NOT EDIT.\n\npackage ui\n\nimport \"github.com/charmbracelet/bubbles/key\"\n\n// KeyMap holds all key bindings for the sequencer.\ntype KeyMap struct {\n")
	for _, s := range c.Sections {
		for _, b := range s.Bindings {
			fmt.Fprintf(&out, "%s key.Binding\n", b.ID)
		}
	}
	out.WriteString("}\n\n// DefaultKeyMap returns the standard key bindings.\nfunc DefaultKeyMap() KeyMap {\nreturn KeyMap{\n")
	for _, s := range c.Sections {
		for _, b := range s.Bindings {
			fmt.Fprintf(&out, "%s: key.NewBinding(key.WithKeys(", b.ID)
			for i, k := range b.Keys {
				if i > 0 {
					out.WriteString(", ")
				}
				fmt.Fprintf(&out, "%q", k)
			}
			fmt.Fprintf(&out, "), key.WithHelp(%q, %q)),\n", b.HelpKey, b.Help)
		}
	}
	out.WriteString("}\n}\n\n// ShortHelp returns key bindings for the short help view.\nfunc (k KeyMap) ShortHelp() []key.Binding {\nreturn []key.Binding{")
	for _, id := range c.ShortHelp {
		fmt.Fprintf(&out, "k.%s,", id)
	}
	out.WriteString("}\n}\n\n// FullHelp returns key bindings for the full help view.\nfunc (k KeyMap) FullHelp() [][]key.Binding {\nreturn [][]key.Binding{\n")
	for _, group := range c.FullHelp {
		out.WriteString("{")
		for _, id := range group {
			fmt.Fprintf(&out, "k.%s,", id)
		}
		out.WriteString("},\n")
	}
	out.WriteString("}\n}\n")
	return format.Source([]byte(out.String()))
}

func renderMarkdown(c config) string {
	var out strings.Builder
	out.WriteString("<!-- Generated from controls.json; run go generate ./... to update. -->\n\n")
	for _, s := range c.Sections {
		fmt.Fprintf(&out, "### %s\n\n", s.Title)
		if s.Intro != "" {
			fmt.Fprintf(&out, "%s\n\n", s.Intro)
		}
		out.WriteString("| Key | Action |\n|---|---|\n")
		for _, b := range s.Bindings {
			labels := make([]string, len(b.Keys))
			for i, k := range b.Keys {
				labels[i] = "<code>" + escapeMarkdown(keyLabel(k)) + "</code>"
			}
			fmt.Fprintf(&out, "| %s | %s |\n", strings.Join(labels, " / "), escapeMarkdown(b.Description))
		}
		out.WriteString("\n")
		if s.Outro != "" {
			fmt.Fprintf(&out, "%s\n\n", s.Outro)
		}
	}
	return out.String()
}

func keyLabel(k string) string {
	labels := map[string]string{"up": "↑", "down": "↓", "left": "←", "right": "→", " ": "Space", "enter": "Enter", "home": "Home", "end": "End", "backspace": "Backspace", "delete": "Delete", "tab": "Tab", "esc": "Esc"}
	if label, ok := labels[k]; ok {
		return label
	}
	if strings.HasPrefix(k, "ctrl+") {
		return "Ctrl+" + strings.ToUpper(strings.TrimPrefix(k, "ctrl+"))
	}
	return k
}

func escapeMarkdown(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "|", "&#124;", "\n", " ", "\r", " ").Replace(s)
}

func updateReadme(readme, content string) (string, error) {
	start, stop := strings.Index(readme, begin), strings.Index(readme, end)
	if strings.Count(readme, begin) != 1 || strings.Count(readme, end) != 1 || stop < start {
		return "", fmt.Errorf("README must contain one ordered pair of key-binding markers")
	}
	return readme[:start+len(begin)] + "\n" + content + readme[stop:], nil
}
